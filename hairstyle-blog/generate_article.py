# --- File Operations ---
def update_index_file(year, month, month_name_kr):
    """Updates the index.html file with a link to the new article."""
    new_link = f'        <li><a href="articles/{year}-{month:02d}.html">{year}년 {month_name_kr}</a></li>'
    
    try:
        with open(index_path, "r", encoding='utf-8') as f:
            content = f.read()
        
        # Check if link already exists
        if f'{year}-{month:02d}.html' in content:
            print(f"Link for {year}년 {month_name_kr} already exists in index.html")
            return
            
        # Add the new link before the placeholder comment
        if "<!-- Links to monthly articles will be added here -->" in content:
            content = content.replace(
                "<!-- Links to monthly articles will be added here -->", 
                f"{new_link}\n        <!-- Links to monthly articles will be added here -->"
            )
        else:
            # If placeholder doesn't exist, add before closing </ul>
            content = content.replace("</ul>", f"    {new_link}\n    </ul>")
        
        with open(index_path, "w", encoding='utf-8') as f:
            f.write(content)
            
        print(f"Added link for {year}년 {month_name_kr} to index.html")
        
    except Exception as e:
        print(f"Error updating index file: {e}")

