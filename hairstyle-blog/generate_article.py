def get_image_for_style(style_name, image_config, image_type="ai_generated_images"):
    """Get image URL for a specific style from configuration."""
    if not image_config:
        return None
    
    # Try exact match first
    if image_type in image_config and style_name in image_config[image_type]:
        return image_config[image_type][style_name]
    
    # Try partial match
    if image_type in image_config:
        for key, url in image_config[image_type].items():
            if key in style_name or style_name in key:
                return url
    
    # Return default image if available
    if "default_image" in image_config:
        if image_type == "ai_generated_images" and "ai_trend" in image_config["default_image"]:
            return image_config["default_image"]["ai_trend"]
        elif image_type == "celebrity_images" and "celebrity" in image_config["default_image"]:
            return image_config["default_image"]["celebrity"]
    
    return None

def generate_content_with_api(prompt, description):
    """Try to generate content with API, fall back to None if failed."""
    if not API_AVAILABLE:
        print(f"API not available, using fallback for {description}")
        return None
        
    try:
        print(f"Generating {description} using Gemini API...")
        response = text_model.generate_content(prompt)
        if response and response.text:
            print(f"{description} generated successfully")
            return response.text
        else:
            print(f"Empty response from API for {description}")
            return None
    except Exception as e:
        print(f"Error generating {description}: {e}")
        return None

